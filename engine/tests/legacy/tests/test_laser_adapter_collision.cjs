'use strict';
const assert=require('node:assert/strict'),catalog=require('../catalog.json'),{Engine}=require('../static/collision-engine.js');
const laser=structuredClone(catalog.kits.find(k=>k.id==='laser-308nm'));
const tiny={id:'tiny',layout:{collisionBoundsMm:{xMin:-1,yMin:-1,xMax:1,yMax:1}}};
const engine=new Engine({kits:[laser,tiny]});
const a={id:'laser-a',kitId:laser.id,xMm:600,yMm:400,rotationDeg:0};
const b={id:'probe',kitId:'tiny',xMm:400,yMm:525,rotationDeg:0};
assert.deepEqual(engine.update([a,b]).pairs,[],'original housing has open space above its long edge');
a.laserAdapter={enabled:true,thicknessMm:17.4};
assert.deepEqual(engine.update([a,b]).pairs,[[a.id,b.id]],'the physical adapter fills this space');
const cached=engine.world(a);
const steady=engine.update(structuredClone([a,b]));
assert.equal(engine.world(a),cached);
assert.equal(steady.stats.last.localCompiles,0);
assert.equal(steady.stats.last.worldTransforms,0);
assert.equal(steady.stats.last.narrowPhaseTests,0);
const unadapted={...a,id:'laser-b',xMm:1600,laserAdapter:undefined};
const probe2={...b,id:'probe-b',xMm:1400};
assert.deepEqual(engine.update([a,b,unadapted,probe2]).pairs,[[a.id,b.id]],'adapter geometry never contaminates an ordinary instance of the same kit');
delete a.laserAdapter;
assert.deepEqual(engine.update([a,b,unadapted,probe2]).pairs,[],'disabling the plate invalidates only its changed shape');
const many=[a,...Array.from({length:499},(_,i)=>({id:`tiny-${i}`,kitId:'tiny',xMm:2000+i*10,yMm:1000,rotationDeg:0}))];
a.laserAdapter={enabled:true,thicknessMm:17.4};engine.update(many);
many[250].xMm+=1;
const moved=engine.update(many);
assert.equal(moved.stats.last.worldTransforms,1,'moving one item in a large layout transforms one item');
assert.equal(moved.stats.last.localCompiles,0);
assert.ok(moved.stats.cache.kits<=3);
assert.equal(moved.stats.cache.instances,500);
engine.invalidateKit(laser.id);
assert.equal(engine.world(a).polygons.length,laser.layout.collisionPolygonsMm.length+1);
console.log('PASS per-instance adapter collisions, cache reuse, toggle cleanup and 500-item incremental update');
